const { _electron: electron } = require('playwright');
const { buildSync } = require('esbuild');
const fs = require('fs/promises');
const { join, resolve } = require('path');
const os = require('os');
const assert = require('assert/strict');
(async () => {
  await fs.mkdir('output', { recursive: true });
  buildSync({ entryPoints: ['tests/fixtures.ts'], outfile: 'output/fixtures.cjs', bundle: true, platform: 'node', format: 'cjs' });
  const { writeApk, textManifest } = require('../output/fixtures.cjs');
  const tmp = await fs.mkdtemp(join(os.tmpdir(), 'hansen-ui-'));
  const fixture = join(tmp, 'fixture.apk'); writeApk(fixture);
  const AdmZip = require('adm-zip');
  const split = join(tmp, 'split.apk'); writeApk(split, textManifest('config.en'));
  const container = new AdmZip(); container.addFile('base.apk', await fs.readFile(fixture)); container.addFile('split.apk', await fs.readFile(split)); const xapk = join(tmp, 'fixture.xapk'); container.writeZip(xapk);
  const env = { ...process.env, XDG_CONFIG_HOME: join(tmp, 'config') }; delete env.ELECTRON_RUN_AS_NODE;
  const executablePath = process.env.HANSEN_EXECUTABLE || require('electron');
  const args = process.env.HANSEN_EXECUTABLE ? [] : [resolve('.')]; if (process.env.HANSEN_TEST_NO_SANDBOX === '1') args.unshift('--no-sandbox');
  let app;
  const errors = [];
  try {
    app = await electron.launch({ executablePath, args, env, timeout: 30000 });
    app.process().stderr.on('data', b => process.stderr.write(b));
    const page = await app.firstWindow();
    page.setDefaultTimeout(30000);
    console.log('Electron production window ready');
    page.on('console', m => { if(m.type() === 'error') console.error('Renderer:', m.text()); });
    page.on('pageerror', e => errors.push(e.message));
    await page.getByRole('heading', { name: 'Understand what you install.' }).waitFor();
    const aboutButtons = page.getByRole('button', { name: 'About Hansen' });
    assert.equal(await aboutButtons.count(), 2);
    await aboutButtons.first().click();
    await page.getByRole('heading', { name: 'Hansen', exact: true }).waitFor();
    await page.getByText('Created by Marcus Hopps').waitFor();
    await page.getByText('Apache License 2.0').waitFor();
    assert.equal(await page.getByText(/deterministic review aids/).count(), 0);
    await page.getByRole('button', { name: 'Close About Hansen' }).click();
    await aboutButtons.last().click();
    await page.getByRole('heading', { name: 'Hansen', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Close About Hansen' }).click();
    const userData = await app.evaluate(({ app }) => app.getPath('userData'));
    assert.ok(userData.startsWith(tmp), `Test settings must be isolated: ${userData}`);
    await page.screenshot({ path: 'output/app-home.png' });
    await page.getByRole('button', { name: /Analysis settings/ }).click();
    assert.equal(await page.getByLabel('Report interpretation').count(), 0);
    await page.getByRole('heading', { name: 'VirusTotal malware reputation' }).waitFor();
    await page.getByRole('button', { name: 'Save settings' }).click();
    await page.getByText('Settings saved. They apply to your next analysis.').waitFor();
    await page.getByRole('button', { name: /Package inspector/ }).click();
    await page.getByRole('heading', { name: 'Understand what you install.' }).waitFor();
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, fixture);
    await page.getByRole('button', { name: /Browse packages/ }).click();
    await page.getByRole('heading', { name: 'Package report', exact: true }).waitFor({ timeout: 30000 });
    const frame = page.frameLocator('iframe');
    await frame.getByRole('heading', { name: /Requested permissions/ }).waitFor();
    const find = page.getByLabel('Find in current view');
    await frame.locator('body').click();
    await page.keyboard.press('Control+f');
    assert.equal(await find.evaluate(element => element === document.activeElement), true);
    assert.equal(await page.locator('.find-bar.floating').count(), 1);
    await find.fill('Requested permissions');
    await page.waitForFunction(() => document.querySelector('.find-count')?.textContent !== '0/0');
    assert.match(await page.locator('iframe').evaluate(element => element.contentDocument.getSelection().toString()), /Requested permissions/i);
    await page.getByRole('button', { name: 'Clear search' }).click();
    assert.equal(await page.locator('.find-bar.floating').count(), 0);
    await frame.getByRole('heading', { name: 'Coverage and limitations' }).waitFor();
    await page.screenshot({ path: 'output/app-report.png' });
    console.log('APK embedded report ready');
    assert.equal(await page.evaluate(() => window.api.listReports().then(r => r.length)), 1);
    // User can cancel the native save dialog and retry without losing the report.
    await app.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }); });
    await page.getByRole('button', { name: /Export PDF/ }).click();
    await page.getByText(/Export cancelled/).waitFor();
    const fixturePdf = resolve('output/fixture-report.pdf');
    await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, fixturePdf);
    await page.getByRole('button', { name: /Export PDF/ }).click();
    await page.getByText(/PDF saved to/).waitFor({ timeout: 30000 });
    assert.ok((await fs.readFile(fixturePdf)).subarray(0,5).equals(Buffer.from('%PDF-')));
    await page.getByRole('button', { name: 'New analysis' }).click();
    await page.evaluate(() => { const input = document.createElement('input'); input.type = 'file'; input.id = 'test-drop-input'; document.body.append(input); });
    await page.locator('#test-drop-input').setInputFiles(xapk);
    await page.evaluate(() => { const input = document.querySelector('#test-drop-input'); const transfer = new DataTransfer(); transfer.items.add(input.files[0]); document.querySelector('.drop-zone').dispatchEvent(new DragEvent('drop', { dataTransfer: transfer, bubbles: true })); input.remove(); });
    await page.getByRole('heading', { name: 'Package report', exact: true }).waitFor({ timeout: 30000 });
    assert.equal(await page.evaluate(() => window.api.listReports().then(r => r.length)), 2);
    console.log('XAPK embedded report ready');
    await page.getByRole('button', { name: /Compare releases/ }).click();
    await page.getByRole('button', { name: 'Compare releases', exact: true }).click();
    await page.getByText(/material package changes|No material changes/).waitFor();
    await page.getByLabel('Find in current view').fill('report');
    await page.waitForFunction(() => document.querySelector('.find-count')?.textContent !== '0/0');
    assert.equal(await page.getByLabel('Find in current view').evaluate(element => element === document.activeElement), true);
    assert.equal(await page.evaluate(() => CSS.highlights.has('hansen-find-current')), true);
    await page.getByLabel('Find in current view').press('Enter');
    assert.equal(await page.getByLabel('Find in current view').evaluate(element => element === document.activeElement), true);
    const afterEnter = await page.locator('.find-count').textContent();
    await page.getByLabel('Find in current view').press('ArrowUp');
    assert.notEqual(await page.locator('.find-count').textContent(), afterEnter);
    await page.getByLabel('Find in current view').press('ArrowDown');
    assert.equal(await page.locator('.find-count').textContent(), afterEnter);
    const compared = await page.evaluate(async () => { const reports = await window.api.listReports(); return window.api.compareReports(reports[1].id, reports[0].id); });
    assert.equal(compared.samePackage, true);
    assert.ok(compared.base.sha256 && compared.target.sha256);
    console.log('Release comparison ready');
    await page.getByRole('button', { name: 'Select' }).click();
    const historyItems = page.locator('.history-item');
    await historyItems.first().click();
    await historyItems.last().click();
    assert.equal(await page.locator('.history-item.checked').count(), 2);
    await page.getByRole('button', { name: 'Clear all' }).click();
    assert.equal(await page.locator('.history-item.checked').count(), 0);
    await page.getByRole('button', { name: 'Select all' }).click();
    await page.getByRole('button', { name: 'Pin', exact: true }).click();
    await page.waitForFunction(() => window.api.listReports().then(reports => reports.length === 2 && reports.every(report => report.pinned)));
    const beforeOrder = await page.evaluate(() => window.api.listReports().then(reports => reports.map(report => report.id)));
    await page.locator('.history-item.pinned').first().dragTo(page.locator('.history-item.pinned').last());
    await page.waitForFunction(order => window.api.listReports().then(reports => reports[0].id === order[1] && reports[1].id === order[0]), beforeOrder);
    await page.getByRole('button', { name: 'Select' }).click();
    await historyItems.first().click();
    await historyItems.last().click();
    await page.evaluate(() => { window.prompt = () => 'Release review'; });
    await page.getByRole('button', { name: 'Edit label' }).click();
    await page.waitForFunction(() => window.api.listReports().then(reports => reports.length === 2 && reports.every(report => report.userLabel === 'Release review')));
    await page.getByRole('button', { name: 'Select' }).click();
    await historyItems.first().click();
    await page.evaluate(() => { window.confirm = () => true; });
    await page.getByRole('button', { name: 'Delete' }).click();
    await page.waitForFunction(() => window.api.listReports().then(reports => reports.length === 1));
    console.log('History multi-selection, pin ordering, labeling and deletion ready');
    await page.reload();
    await page.locator('.history-item').first().click();
    await page.getByRole('heading', { name: 'Package report', exact: true }).waitFor();
    await page.getByRole('button', { name: 'New analysis' }).click();
    const requestedSample = resolve(process.argv[2] || '../TikTok+-+Videos,+Shop+&+LIVE_47.1.4_APKPure.apk');
    const sample = await fs.stat(requestedSample).then(() => requestedSample, () => fixture);
    const hasRealSample = sample === requestedSample;
    // Exercise worker cancellation and immediate subsequent analysis.
    const cancelled = await page.evaluate(async file => { const task = window.api.analyzeApk(file).then(() => 'unexpected success', e => String(e)); await new Promise(r => setTimeout(r, 20)); await window.api.cancelAnalysis(); return task; }, sample);
    assert.match(cancelled,/cancelled/);
    console.log('Cancellation confirmed:', cancelled);
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, sample);
    await page.getByRole('button', { name: /Browse packages/ }).click();
    await page.getByRole('heading', { name: 'Package report', exact: true }).waitFor({ timeout: 300000 });
    console.log('Post-cancellation APK report ready');
    await page.frameLocator('iframe').getByRole('heading', { name: hasRealSample ? /com.zhiliaoapp.musically/ : /com.example.fixture/ }).waitFor();
    await page.screenshot({ path: 'output/app-sample-report.png' });
    const samplePdf = resolve('output/tiktok-hansen-report.pdf');
    await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, samplePdf);
    await page.getByRole('button', { name: /Export PDF/ }).click();
    await page.getByText(/PDF saved to/).waitFor({ timeout: 60000 });
    assert.ok((await fs.stat(samplePdf)).size > 10000);
    const reports = await page.evaluate(() => window.api.listReports());
    const expectedPackage = hasRealSample ? 'com.zhiliaoapp.musically' : 'com.example.fixture';
    const sampleSummary = reports.find(report => report.packageName === expectedPackage && !report.pinned) || reports.find(report => report.packageName === expectedPackage);
    assert.ok(sampleSummary);
    const actual = await page.evaluate(id => window.api.getReport(id), sampleSummary.id);
    await fs.writeFile('output/electron-sample-report.json', JSON.stringify(actual, null, 2));
    assert.equal(actual.context.versionName, hasRealSample ? '47.1.4' : '1.0');
    assert.ok(actual.context.permissions.length > 0);
    assert.equal(actual.packages[0].manifest.packageName, hasRealSample ? 'com.zhiliaoapp.musically' : 'com.example.fixture');
    assert.deepEqual(errors, []);
    await app.close();
    app = await electron.launch({ executablePath, args, env, timeout: 30000 });
    const reopened = await app.firstWindow();
    await reopened.locator('.history-item').first().waitFor();
    assert.equal(await reopened.locator('.history-item').count(), 2);
    await reopened.locator('.history-item', { hasText: actual.context.packageName }).last().click();
    await reopened.frameLocator('iframe').getByRole('heading', { name: actual.context.packageName, exact: true }).waitFor();
    assert.equal(await reopened.evaluate(() => window.api.getSettings().then(s => s.virusTotalEnabled)), false);
    console.log(JSON.stringify({ status: 'passed', tests: ['production launch','both about splash entry points','settings','APK picker and embedded report','PDF cancellation and retry','XAPK drag/drop split report','release comparison','history multi-selection and select all','pin persistence and drag ordering','history labeling and deletion','history after reload and app restart','worker cancellation','post-cancellation analysis','full PDF export','no renderer exceptions'], userDataIsolated: true, samplePackage: actual.context.packageName, sampleDurationMs: actual.durationMs, samplePdf, reportCount: reports.length }, null, 2));
  } finally { if (app) await app.close(); await fs.rm(tmp, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
